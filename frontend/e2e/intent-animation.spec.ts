import {test,expect} from '@playwright/test'
test('chat streams as plain text without starting the compiler or tutorial tabs',async({page})=>{
 await page.route('**/api/conversations**',route=>route.fulfill({json:route.request().method()==='POST'?{id:'chat-test',title:'对话',updated:1}:[]}))
 await page.route('**/generate',route=>route.fulfill({contentType:'text/event-stream',body:'event: start\ndata: {"id":"chat-r","kind":"chat","state":{},"mode":"live"}\n\nevent: source\ndata: {"value":"你好！想聊哪个算法？"}\n\nevent: done\ndata: {"status":"complete"}\n\n'}))
 const workers:string[]=[];page.on('worker',worker=>workers.push(worker.url()))
 await page.goto('/')
 await page.getByRole('textbox',{name:'输入教程需求'}).fill('你好')
 await page.getByRole('button',{name:'发送',exact:true}).click()
 await expect(page.locator('.chat-reply')).toHaveText('你好！想聊哪个算法？')
 await expect(page.getByRole('tab',{name:'交互教程',exact:true})).toHaveCount(0)
 expect(workers).toEqual([])
})
test('flow diagram moves continuously, pauses, resumes and reacts to node selection',async({page})=>{
 const source='{@body const [selected,setSelected]=DIL.useState("q")}\n<flow-diagram label="注意力流动" nodes={[{id:"q",label:"Query",x:100,y:180},{id:"k",label:"Key",x:500,y:180}]} edges={[{from:"q",to:"k",weight:selected==="q"?0.8:0.2,label:selected==="q"?"0.8":"0.2"}]} selected={selected} onSelect={setSelected} animated={true}/>'
 const c={id:'flow-test',title:'连续动画验收',updated:1,revisions:[{id:'flow-r',kind:'lesson',prompt:'生成动图',source,state:{},mode:'live',status:'complete',created:1}]}
 await page.route('**/api/conversations**',route=>route.fulfill({json:route.request().method()==='PUT'?{ok:true}:new URL(route.request().url()).pathname==='/api/conversations'?[c]:c}))
 await page.goto('/')
 await page.getByRole('button',{name:'连续动画验收',exact:true}).click()
 const particle=page.locator('.flow-particle')
 await expect(particle).toBeVisible()
 const position=()=>particle.evaluate(el=>{const m=(el as unknown as SVGGraphicsElement).getCTM()!;return [m.e,m.f]})
 const first=await position();await expect.poll(position).not.toEqual(first)
 await page.getByRole('button',{name:'暂停动画',exact:true}).click()
 await expect(page.locator('.flow-diagram')).toHaveAttribute('data-playing','false')
 const paused=await position();await page.waitForTimeout(250);expect(await position()).toEqual(paused)
 await page.getByRole('button',{name:'Key',exact:true}).click()
 await expect(page.locator('.flow-edge')).toHaveAttribute('data-weight','0.2')
 await page.getByRole('button',{name:'播放动画',exact:true}).click()
 await expect.poll(position).not.toEqual(paused)
 await page.locator('.flow-diagram').screenshot({path:'../data/diagnostics/flow-animation.png'})
})

 test('real model attention animation computes new weights and fits narrow screens',async({page})=>{
 const {readFileSync}=await import('node:fs')
 const source=readFileSync('test-fixtures/attention-flow.dil','utf8')
 const c={id:'real-flow',title:'真实注意力动画',updated:1,revisions:[{id:'real-flow-r',kind:'lesson',prompt:'生成动画',source,state:{},mode:'live',status:'complete',created:1}]}
 await page.route('**/api/conversations**',route=>route.fulfill({json:route.request().method()==='PUT'?{ok:true}:new URL(route.request().url()).pathname==='/api/conversations'?[c]:c}))
 await page.goto('/')
 await page.getByRole('button',{name:'真实注意力动画',exact:true}).click()
 await expect(page.locator('.flow-node')).toHaveCount(6)
 await expect(page.locator('.lesson-issues')).toHaveCount(0)
 const weights=()=>page.locator('.flow-edge').evaluateAll(els=>els.slice(0,4).map(el=>Number(el.getAttribute('data-weight'))))
 const initial=await weights();expect(initial.reduce((a,b)=>a+b,0)).toBeCloseTo(1,8)
 await page.getByRole('button',{name:'学习 (Key)',exact:true}).click()
 await expect.poll(weights).not.toEqual(initial)
 const next=await weights();expect(next.reduce((a,b)=>a+b,0)).toBeCloseTo(1,8)
 await page.getByLabel('动画速度').selectOption('2')
 await expect(page.locator('animateMotion').first()).toHaveAttribute('dur','1.5s')
 const bounds=await page.getByRole('button',{name:'暂停动画',exact:true}).boundingBox();expect(bounds!.width).toBeLessThan(120)
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
 await page.locator('.flow-diagram').screenshot({path:'../data/diagnostics/real-flow-mobile.png'})
 })
