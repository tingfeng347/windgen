import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'
test('gradient lesson, latest snapshot, version restore and responsive layout',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/')
  await page.getByRole('button',{name:'梯度下降 沿损失地形观察参数更新'}).click()
  await expect(page.getByText('斜率 w',{exact:true})).toBeVisible()
  await expect(page.getByTestId('step-value')).toHaveText('0 / 40')
  await page.getByRole('button',{name:'单步',exact:true}).click()
  await expect(page.getByTestId('step-value')).toHaveText('1 / 40')
  await expect(page.getByText('0.433333',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'播放',exact:true}).click()
  await expect(page.getByTestId('step-value')).not.toHaveText('1 / 40')
  await page.getByRole('button',{name:'暂停',exact:true}).click()
  const step=await page.getByTestId('step-value').innerText()
  let submitted:any
  await page.route('**/api/conversations/*/generate',async route=>{
    submitted=route.request().postDataJSON()
    const source='<!-- windgen-state: {"set":{"learningRate":0.2},"reset":["step"]} -->\n'+readFileSync('../examples/gradient.dil','utf8')
    const id='browser-mock-revision'
    const body=`event: start\ndata: ${JSON.stringify({id,state:submitted.state,mode:'live'})}\n\nevent: source\ndata: ${JSON.stringify({value:source})}\n\nevent: done\ndata: ${JSON.stringify({id,status:'complete'})}\n\n`
    await route.fulfill({status:200,contentType:'text/event-stream',body})
  })
  await page.route('**/api/conversations/*/revisions/browser-mock-revision/state',route=>route.fulfill({status:200,contentType:'application/json',body:'{"ok":true}'}))
  await page.getByRole('textbox',{name:'输入教程需求'}).fill('把学习率改成0.2')
  await page.getByRole('button',{name:'发送',exact:true}).click()
  await expect(page.getByTestId('step-value')).toHaveText('0 / 40')
  expect(submitted.state.step).toBe(Number(step.split('/')[0]))
  await page.getByRole('tab',{name:'状态',exact:true}).click()
  await expect(page.locator('.source-view')).toContainText('"learningRate": 0.2')
  await page.getByRole('tab',{name:'交互教程'}).click()
  await page.getByRole('button',{name:'演示 1',exact:true}).click()
  await expect(page.getByTestId('step-value')).toHaveText(step)
  await page.locator('.scene-wrap').scrollIntoViewIfNeeded()
  await page.screenshot({path:'test-results/desktop.png',fullPage:true})
  await page.setViewportSize({width:390,height:844})
  await expect(page.getByRole('button',{name:'打开会话栏'})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.locator('.scene-wrap').scrollIntoViewIfNeeded()
  await page.screenshot({path:'test-results/mobile.png',fullPage:true})
  expect(errors).toEqual([])
})
